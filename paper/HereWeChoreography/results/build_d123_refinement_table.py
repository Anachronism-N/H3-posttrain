"""Recompute the published refinement ratings; no inference or missing-score imputation."""
from pathlib import Path
import hashlib
import json
import statistics

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "results/d123_refine_v1"


def main():
    manifest = json.loads((SOURCE / "manifest.json").read_text(encoding="utf-8"))
    provenance = json.loads((SOURCE / "provenance.json").read_text(encoding="utf-8"))
    judgments = [json.loads(line) for line in (SOURCE / "judgments.jsonl").read_text(encoding="utf-8").splitlines()]
    outputs = [json.loads(line) for line in (SOURCE / "outputs.jsonl").read_text(encoding="utf-8").splitlines()]
    assert len(judgments) == len(outputs) == manifest["cases"] == 2000
    assert len({row["case_id"] for row in judgments}) == 2000
    for name, digest in manifest["artifacts_sha256"].items():
        assert hashlib.sha256((SOURCE / name).read_bytes()).hexdigest() == digest
    tex = r"""% Generated by results/build_d123_refinement_table.py from public per-case scores.
\begin{table*}[t]
\centering
\caption{Published ratings for SFT v3 + refine-v1 on 2,000 clips. Cells show the mean (valid count); scores are on 1--5. Rows use different rating versions on the same outputs. Source D1--D3 IDs await confirmation against our anchors; v2.1 was defined after earlier test results. D4--D6 remain unreported (``--'', not zero).}
\label{tab:refinement-d123}
\begingroup\small
\setlength{\tabcolsep}{5pt}
\renewcommand{\arraystretch}{1.10}
\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}llrrrrrr@{}}
\toprule
Method & Rating version & D1 & D2 & D3 & D4 & D5 & D6 \\
\midrule
"""
    summaries = {}
    for version in ("r4", "v2.1"):
        cells = ["SFT v3 + refine-v1", version]
        summaries[version] = {}
        for dimension in ("D1", "D2", "D3"):
            valid = [r["scores"][version][dimension]["score"] for r in judgments
                     if r["scores"][version][dimension]["status"] == "valid_structure"
                     and r["scores"][version][dimension]["score"] is not None]
            assert all(type(value) is int and 1 <= value <= 5 for value in valid)
            mean = statistics.mean(valid)
            expected = provenance["scores"][version]["dimensions"][dimension]
            assert len(valid) == expected["valid"] and abs(mean - expected["available_mean"]) < 1e-12
            cells.append(f"{mean:.2f} ({len(valid):,})")
            summaries[version][dimension] = dict(mean=mean, valid=len(valid), registered=2000)
        tex += " & ".join(cells + ["--", "--", "--"]) + r" \\" + "\n"
    tex += r"""\bottomrule
\end{tabular*}
\endgroup
\end{table*}
"""
    (ROOT / "tables/refinement_d123.tex").write_text(tex, encoding="utf-8")
    receipt = dict(source_commit=provenance["commit"], method=manifest["method"],
                   editor_model=manifest["editor_model"], summaries=summaries,
                   missing_dimensions=["D4", "D5", "D6"],
                   protocol_mapping_verified=False, baseline_comparison_available=False)
    (ROOT / "results/d123_refine_v1/table.source.json").write_text(
        json.dumps(receipt, ensure_ascii=False, indent=2)+"\n", encoding="utf-8")
    print(json.dumps(receipt, indent=2))


if __name__ == "__main__":
    main()
