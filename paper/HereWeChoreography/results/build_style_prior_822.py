"""Build the active style table using only the archived 822-clip population.

Run: python results/build_style_prior_822.py
No inference, resampling, case selection, or source-result modification occurs.
The older multi-population builder is archived and no longer a manuscript input.
"""
from pathlib import Path
import hashlib
import json
import math

ROOT = Path(__file__).resolve().parents[1]
FILES = {"comparison": "baselines822-comparison-v1.json",
         "status": "pilot_final_status_v1.json", "audit": "preview-audit-v1.json"}
BASELINES = [("qwen3-omni-instruct", "Qwen3-Omni-Instruct"),
             ("moss-audio", "MOSS-Audio"), ("moss-music", "MOSS-Music"),
             ("music-flamingo", "Music-Flamingo"), ("audio-flamingo3", "Audio-Flamingo3"),
             ("af-next-instruct", "Audio-Flamingo-Next"), ("qwen25-omni", "Qwen2.5-Omni")]
TRAINED = [("ce", "MuQ-JEV head: CE"), ("weighted-ce", "MuQ-JEV head: weighted CE"),
           ("focal-gamma2", "MuQ-JEV head: focal")]
METRICS = ["top1", "top3", "macro_f1", "balanced_accuracy"]


def main():
    sources = {key: json.loads((ROOT / "results" / name).read_text(encoding="utf-8-sig"))
               for key, name in FILES.items()}
    data, status, audit = (sources[key] for key in FILES)
    assert data["schema"] == "full22-zero-shot-baselines822-comparison-v1"
    assert set(data["points"]) == {key for key, _ in BASELINES + TRAINED}
    assert data["registered"] == sum(data["label_support"].values()) == 822
    assert set(data["supported_classes"]) == {k for k, v in data["label_support"].items() if v > 0}
    assert len(data["supported_classes"]) == 13
    assert status["output_dimensions"] == len(data["label_support"]) == 22
    assert status["supported_training_classes"] == 15 and status["full22_training_ready"] is False
    assert status["preview_metrics"]["denominator"] == audit["preview_counts"]["all"] == 822
    assert status["preview_metrics"]["positive_gt_classes"] == audit["preview_only_supported_gt_classes"] == 13
    assert audit["all2822_prediction_identities_verified"] is True
    assert audit["three_frozen_models_sha_verified"] is True
    assert audit["no_training_or_hyperparameter_update"] is True
    rows = []
    for method, name in BASELINES + TRAINED:
        metrics = {key: data["points"][method]["supported"][key] for key in METRICS}
        assert all(type(v) in (int, float) and math.isfinite(v) and 0 <= v <= 1 for v in metrics.values())
        assert metrics["top1"] <= metrics["top3"]
        if method in {key for key, _ in TRAINED}:
            cross = status["preview_metrics"][method]
            for metric in METRICS:
                key = metric if metric in ("top1", "top3") else "supported_" + metric
                assert math.isclose(metrics[metric], cross[key], abs_tol=1e-12, rel_tol=0)
        rows.append(dict(method_id=method, display_name=name, metrics=metrics,
                         regime="zero-shot" if len(rows) < len(BASELINES) else "supervised"))
    maxima = {key: max(row["metrics"][key] for row in rows) for key in METRICS}
    tex = r"""% Generated by results/build_style_prior_822.py; only the 822-clip population.
\begin{table*}[t]
\centering
\caption{Audio-only dance-style agreement on 822 clips with video-VLM pseudo-labels. Rankings use 22 labels; Macro-F1 (MF1) and balanced accuracy (BA) average over the 13 observed classes. Supervised heads and zero-shot models have different training access. Values are $\times100$; bold marks column maxima, not significance.}
\label{tab:style-prior-822}
\begingroup\small
\setlength{\tabcolsep}{5pt}
\renewcommand{\arraystretch}{1.08}
\begin{tabular*}{0.90\textwidth}{@{\extracolsep{\fill}}lrrrr@{}}
\toprule
Method & Top-1 & Top-3 & MF1 & BA \\
\midrule
\multicolumn{5}{l}{\emph{Zero-shot audio-language models}} \\
"""
    for index, row in enumerate(rows):
        if index == len(BASELINES):
            tex += r"\midrule" + "\n" + r"\multicolumn{5}{l}{\emph{Supervised style heads; frozen MuQ encoder}} \\" + "\n"
        cells = [row["display_name"]]
        for key in METRICS:
            value = row["metrics"][key]
            formatted = f"{100 * value:.2f}"
            if math.isclose(value, maxima[key], abs_tol=1e-12, rel_tol=0):
                formatted = r"\textbf{" + formatted + "}"
            cells.append(formatted)
        tex += " & ".join(cells) + r" \\" + "\n"
    tex += r"""\bottomrule
\end{tabular*}
\endgroup
\end{table*}
"""
    assert len(rows) == 10 and tex.count("{") == tex.count("}")
    table = ROOT / "tables/style_prior_822.tex"
    table.write_text(tex, encoding="utf-8")
    metadata = dict(schema="paper.style_prior_822.v1", source_files={
        key: dict(path="results/" + name,
                  sha256=hashlib.sha256((ROOT / "results" / name).read_bytes()).hexdigest())
        for key, name in FILES.items()}, metric_storage="fractions", display_scale=100,
        rows=rows, maxima=maxima, numeric_cells=40,
        population_scope=dict(cases=822, supported_classes=13, outputs=22, training_supported_classes=15),
        provenance_limit="Archived identity fields checked; raw case identities are not independently revalidated here.",
        selection="All seven zero-shot models and all three training objectives on the same 822 registered clips.",
        interpretation="Video pseudo-label agreement, not human music suitability or downstream harness benefit.",
        manuscript_scope="Only the 822-clip population is included; older populations remain archived.")
    (ROOT / "results/style_prior_822.source.json").write_text(
        json.dumps(metadata, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(dict(table=str(table), rows=len(rows), numeric_cells=40), indent=2))


if __name__ == "__main__":
    main()
